def roles_by_team(script: str) -> dict[str, tuple[RoleDefinition, ...]]:
    roles = SCRIPT_ROLES[script]
    return {
        team: tuple(item for item in roles if item.team == team)
        for team in ("townsfolk", "outsider", "minion", "demon")
    }
